package input

import (
	"os"
	"path/filepath"
	"testing"
)

// TestLoadImageRefNotImage verifies a non-image path returns false.
func TestLoadImageRefNotImage(t *testing.T) {
	_, ok := loadImageRef("", "readme.md")
	if ok {
		t.Error("expected false for .md file")
	}
}

// TestLoadImageRefNonexistent verifies a missing image file returns false.
func TestLoadImageRefNonexistent(t *testing.T) {
	_, ok := loadImageRef("", "/nonexistent/path/test.png")
	if ok {
		t.Error("expected false for nonexistent file")
	}
}

// TestLoadImageRefRealImage verifies a real image file loads with FileName.
func TestLoadImageRefRealImage(t *testing.T) {
	dir := t.TempDir()
	pngPath := filepath.Join(dir, "inigambarsaya.png")
	pngData := []byte{
		0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
		0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
		0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
		0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
		0x89, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x44, 0x41,
		0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00,
		0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00,
		0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE,
		0x42, 0x60, 0x82,
	}
	if err := os.WriteFile(pngPath, pngData, 0o644); err != nil {
		t.Fatalf("write temp png: %v", err)
	}
	img, ok := loadImageRef(dir, "inigambarsaya.png")
	if !ok {
		t.Fatal("expected loadImageRef to succeed for real png")
	}
	if img.FileName != "inigambarsaya.png" {
		t.Errorf("FileName = %q, want inigambarsaya.png", img.FileName)
	}
}

